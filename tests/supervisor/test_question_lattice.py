class TestEnumeration:
    def test_deterministic_and_prefix(self) -> None:
        a, _ = first(lattice().enumerate(["Customer", "Sale"], max_hops=2), 120)
        b, _ = first(lattice().enumerate(["Sale", "Customer"], max_hops=2), 40)
        assert [q.question_key for q in b] == [q.question_key for q in a[:40]]
        assert len({q.question_key for q in a}) == len(a)

    def test_order_starts_with_top_then_bottom(self) -> None:
        qs, complete = first(lattice().enumerate(["Customer", "Sale"], max_hops=1), 3)
        assert complete is False
        top, bottom = qs[0].skeleton, qs[1].skeleton
        assert top.where == ((), True) and top.band2 is None and top.band3 is None
        assert bottom.where == ((), False)
        assert qs[0].summary == (
            "ANCHORS Customer a1, Sale a2 | JOIN a1 -[placed]-> a2 | WHERE TRUE"
        )

    def test_every_emitted_skeleton_is_a_member(self) -> None:
        lat = lattice()
        qs, _ = first(lat.enumerate(["Customer", "Sale"], max_hops=2), 200)
        assert all(lat.contains(q.skeleton) for q in qs)
        assert all(lat.key(q.skeleton) == q.question_key for q in qs)
        assert any(q.skeleton.band2 is not None for q in qs)
        assert any(q.skeleton.band3 is not None for q in qs)

    def test_question_key_is_the_section_8_14_key(self) -> None:
        lat = lattice()
        [q] = first(lat.enumerate(["Customer", "Sale"], max_hops=1), 1)[0]
        expected = canonical_hash(CANON_VERSION, lat.version, dag_hash(q.skeleton), ())
        assert q.question_key == expected

    def test_key_depends_on_the_schema(self) -> None:
        [a] = first(lattice().enumerate(["Customer", "Sale"], max_hops=1), 1)[0]
        other = lattice(shop(FactlessFact("Sale")))
        [b] = first(other.enumerate(["Customer", "Sale"], max_hops=1), 1)[0]
        assert a.skeleton == b.skeleton and a.question_key != b.question_key

    def test_skeleton_round_trips_through_json(self) -> None:
        qs, _ = first(lattice().enumerate(["Customer", "Sale"], max_hops=2), 200)
        assert all(Skeleton.from_json(q.skeleton.to_json()) == q.skeleton for q in qs)

    def test_three_anchors_reuse_bound_aliases(self) -> None:
        qs, _ = first(
            lattice().enumerate(["Customer", "Product", "Sale"], max_hops=2), 1
        )
        placed = ("Customer", "placed", "Sale", "+")
        assert qs[0].skeleton.join == (
            ("a1", (placed, ("Product", "included_in", "Sale", "-"))),
            ("a1", (placed,)),
        )
        space = lattice().space(["Customer", "Product", "Sale"], max_hops=2)
        # A later PathJoin may start at a position alias of an earlier one.
        assert lattice().contains(
            Skeleton(
                space.anchor_names,
                (
                    ("a1", (placed, ("Product", "included_in", "Sale", "-"))),
                    (
                        "p2_1",
                        (
                            ("Product", "included_in", "Sale", "-"),
                            ("Product", "included_in", "Sale", "+"),
                        ),
                    ),
                ),
            )
        )

    def test_hop_bound_limits_patterns(self) -> None:
        # Customer and Product meet only through Sale: two hops are needed.
        with pytest.raises(InvalidAnchors):
            lattice().space(["Customer", "Product"], max_hops=1)
        qs, _ = first(lattice().enumerate(["Customer", "Product"], max_hops=2), 1)
        assert len(qs[0].skeleton.join[0][1]) == 2


class TestTyping:
    def _ctx(self, schema: DGMSchema) -> JoinCtx:
        space = lattice(schema).space(["Customer", "Sale"], max_hops=1)
        return JoinCtx(space, (("a1", (("Customer", "placed", "Sale", "+"),)),))

    def test_atoms_respect_section_4_1(self) -> None:
        atoms = self._ctx(shop()).where_universe
        assert ("cmp", ("prop", "a2", "revenue"), ">", ("param", "Real")) in atoms
        # String and Real are never compared; Ref pairs are in canonical order.
        assert not any(
            a[0] == "cmp" and a[3] == ("prop", "a2", "revenue") for a in atoms
        )
        modes = {a[2] for a in atoms if a[0] == "path"}
        assert modes == {"EVENTUALLY", "GLOBALLY", "NEXT", "UNTIL"}  # no past mode

    def test_aggregates_respect_section_4_2_and_factless(self) -> None:
        aggs = self._ctx(shop()).agg_terms
        assert ("agg", "SUM", ("prop", "a2", "revenue")) in aggs
        assert ("agg", "SUM", ("prop", "a1", "region")) not in aggs
        assert ("agg", "MAX", ("prop", "a1", "region")) in aggs
        factless = self._ctx(shop(FactlessFact("Sale"))).agg_terms
        assert ("agg", "SUM", ("prop", "a2", "revenue")) not in factless
        assert ("agg", "COUNT", ("prop", "a2", "revenue")) in factless

    def test_bronze_types_are_not_group_keys(self) -> None:
        bronze = MedallionLayer("Customer", MedallionLayerKind.BRONZE)
        keys = self._ctx(shop(bronze)).group_keys
        assert keys == (("prop", "a2", "revenue"),)


class TestDrillAcross:
    def schema(self, conformed: bool) -> DGMSchema:
        sigma = (Conformed("Customer", {"Sale", "Return"}),) if conformed else ()
        return model(
            (
                NodeType("Customer", DIM, {"region": S}),
                NodeType("Sale", FACT, {"revenue": R}),
                NodeType("Return", FACT, {"amount": R}),
            ),
            (
                EdgeType("Customer", "Sale", "placed", VERB),
                EdgeType("Customer", "Return", "made", VERB),
            ),
            sigma,
        )

    def ctx(self, conformed: bool) -> JoinCtx:
        space = lattice(self.schema(conformed)).space(["Return", "Sale"], max_hops=2)
        join = (
            (
                "a1",
                (
                    ("Customer", "made", "Return", "-"),
                    ("Customer", "placed", "Sale", "+"),
                ),
            ),
        )
        return JoinCtx(space, join)

    def test_conformed_dimension_splits_branches(self) -> None:
        ctx = self.ctx(conformed=True)
        cross = ("cmp", ("prop", "a1", "amount"), "<", ("prop", "a2", "revenue"))
        assert cross not in ctx.where_universe  # DA3
        assert ctx.group_keys == (("prop", "p2_1", "region"),)  # DA2
        assert ("agg", "COUNT", ("node", "p2_1")) not in ctx.agg_terms  # DA1

    def test_without_conformance_it_is_one_branch(self) -> None:
        ctx = self.ctx(conformed=False)
        cross = ("cmp", ("prop", "a1", "amount"), "<", ("prop", "a2", "revenue"))
        assert cross in ctx.where_universe


