J = (("a1", (("Customer", "placed", "Sale", "+"),)),)
SEGMENT = ("cmp", ("prop", "a1", "segment"), "=", ("param", "String"))


def by(key: str, fn: str, retail: bool) -> Skeleton:
    where = ((SEGMENT,), (0, False, True)) if retail else ((), True)
    band2 = (
        (("prop", "a1", key),),
        (("agg", fn, ("prop", "a2", "revenue")),),
        ((), True),
    )
    return Skeleton(("Customer", "Sale"), J, where, band2)


RR = by("region", "SUM", True)  # revenue by region, Where segment = 'retail'
R = by("region", "SUM", False)  # revenue by region
CR = by("country", "SUM", True)  # revenue by country, Where retail
OC = by("country", "COUNT", False)  # order count by country


class _Schemas:
    def __init__(self, schemas: dict[str, DGMSchema]) -> None:
        self.schemas = schemas

    def __call__(self, dataset: str) -> DGMSchema:
        return self.schemas[dataset]


def graph(*skeletons: Skeleton) -> tuple[LatticeMoveGraph, QuestionLattice]:
    lat = lattice(h=4)
    index = SkeletonIndex()
    for sk in skeletons:
        index.put(lat.key(sk), sk)
    return LatticeMoveGraph(_Schemas({"sales": shop()}), index), lat


class TestMoveGraph:
    def test_adr_0007_example_distances(self) -> None:
        moves, lat = graph(RR)
        rr, r, cr, oc = (lat.key(x) for x in (RR, R, CR, OC))
        assert moves.contains("sales", rr)
        near = within_distance(moves, "sales", rr, 2)
        assert near[r] == 1  # remove one atom
        assert near[cr] == 1  # replace one GroupBy key
        assert oc not in near  # three moves away
        frontier = [q for q, d in near.items() if d == 2]
        assert any(oc in moves.neighbours("sales", q) for q in frontier)  # d_S = 3

    def test_moves_are_symmetric(self) -> None:
        moves, lat = graph(RR)
        rr = lat.key(RR)
        for q in moves.neighbours("sales", rr):
            assert rr in moves.neighbours("sales", q)

    def test_neighbours_are_deterministic_members(self) -> None:
        lat = lattice(h=4)
        a = [q.question_key for q in lat.neighbours(RR)]
        assert a == [q.question_key for q in lattice(h=4).neighbours(RR)]
        assert all(lat.contains(q.skeleton) for q in lat.neighbours(RR))

    def test_replacing_a_hop(self) -> None:
        schema = model(
            (NodeType("Date", DIM), NodeType("Sale", FACT)),
            (
                EdgeType("Date", "Sale", "ordered_on", VERB),
                EdgeType("Date", "Sale", "shipped_on", VERB),
            ),
        )
        lat = lattice(schema)
        [top] = first(lat.enumerate(["Date", "Sale"], max_hops=1), 1)[0]
        joins = {q.skeleton.join for q in lat.neighbours(top.skeleton)}
        assert (("a1", (("Date", "shipped_on", "Sale", "+"),)),) in joins

    def test_other_anchor_set_is_another_component(self) -> None:
        moves, lat = graph(RR)
        [other] = first(lat.enumerate(["Product", "Sale"], max_hops=1), 1)[0]
        assert other.question_key not in within_distance(moves, "sales", lat.key(RR), 2)

    def test_unknown_key_cannot_be_decided(self) -> None:
        from sqldim.core.query.dgm.nl.supervisor._tools_kb import MoveGraphUnsupported

        moves, _ = graph()
        with pytest.raises(MoveGraphUnsupported):
            moves.contains("sales", "0" * 64)

    def test_key_of_another_schema_is_not_a_vertex(self) -> None:
        other = lattice(shop(FactlessFact("Sale")), h=4)
        index = SkeletonIndex()
        index.put(other.key(R), R)
        moves = LatticeMoveGraph(_Schemas({"sales": shop()}), index)
        assert moves.contains("sales", other.key(R)) is False

    def test_index_survives_process_recreation(self, tmp_path: Path) -> None:
        path = tmp_path / "skeletons.sqlite"
        first_index = SkeletonIndex(path)
        first_index.put("k", RR)
        first_index.close()
        again = SkeletonIndex(path)
        assert again.get("k") == RR
        again.close()


