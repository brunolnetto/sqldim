    def test_growth_enumerates_stores_and_retrieves(self, kb: Any) -> None:
        from sqldim.application.supervisor_host import _open_bundled

        rt = make_runtime(auth({"growth": RW}), _open_bundled, budget(), kb=kb)
        args = {
            "dataset": "growth",
            "anchors": ["SaaSUser", "Session"],
            "max_hops": 1,
            "limit": 10,
        }

        def run(*steps: ToolCallRequest) -> Any:
            planner = ScriptedPlanner(
                lambda view: plan(*steps, plan_id=view.plan_id, version=view.version)
            )
            return run_supervisor("g", dataclasses.replace(rt, planner=planner))

        listed = run(step("w", TOOL, args, fraction=1.0))
        assert listed.outcome is Outcome.COMPLETE, listed
        data = listed.results["w"].data
        assert data["complete"] is False and len(data["questions"]) == 10
        top = data["questions"][0]["question_key"]
        assert data["questions"][0]["skeleton"].endswith("WHERE TRUE")
        one_atom = next(
            q["question_key"]
            for q in data["questions"]
            if q["skeleton"].count(" | ") == 2
            and "WHERE TRUE" not in q["skeleton"]
            and "WHERE FALSE" not in q["skeleton"]
            and not any(w in q["skeleton"] for w in ("NOT ", " AND ", " OR "))
        )
        finding = {
            "question_key": one_atom,
            "parameters": {},
            "datasets": ["growth"],
            "content": "sessions with a filter",
        }
        state = run(
            step("s", "dgm_store_finding", {"finding": finding}, fraction=0.5),
            step(
                "r",
                "dgm_retrieve_related",
                {"dataset": "growth", "question_key": top, "parameters": {}, "k": 1},
                depends_on=["s"],
                fraction=0.5,
            ),
        )
        assert state.outcome is Outcome.COMPLETE, state
        stored = state.results["s"].data["finding_id"]
        assert state.results["r"].data["findings"] == [
            {"finding_id": stored, "d_S": 1, "d_P": None}
        ]
