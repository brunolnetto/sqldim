class TestBooleanFunctions:
    @pytest.mark.parametrize("n,count", [(0, 2), (1, 4), (2, 16), (3, 256)])
    def test_sizes_list_every_function_exactly_once(self, n: int, count: int) -> None:
        fs = [
            f for t in range(_bdd.max_size(n) + 1) for f in _bdd.functions_of_size(t, n)
        ]
        assert len(fs) == count == len(set(fs))
        assert all(_bdd.is_canonical(f, n) for f in fs)
        assert all(
            _bdd.size(f) == t for t in range(4) for f in _bdd.functions_of_size(t, n)
        )

    def test_order_starts_with_true_then_false(self) -> None:
        assert list(_bdd.functions_of_size(0, 3)) == [True, False]

    def test_remap_is_a_renaming(self) -> None:
        f = (0, False, (1, True, False))  # x0 ∧ ¬x1
        assert _bdd.remap(f, [1, 0]) == (0, (1, False, True), False)  # ¬x0 ∧ x1


