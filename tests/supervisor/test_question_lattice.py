"""Σ kinds the enumeration reads, stated completely by the fixtures."""
S, R = PropType("String"), PropType("Real")
DIM, FACT, VERB = NodeKind.DIM, NodeKind.FACT, EdgeKind.VERB


def model(nodes: Any, edges: Any, sigma: Any = (), kinds: Any = KINDS) -> DGMSchema:
    return DGMModel(node_types=nodes, edge_types=edges, sigma=sigma, sigma_kinds=kinds)


def shop(*sigma: Any, kinds: Any = KINDS) -> DGMSchema:
    """Customer → Sale ← Product; Region is isolated."""
    return model(
        (
            NodeType("Customer", DIM, {"country": S, "region": S, "segment": S}),
            NodeType("Sale", FACT, {"revenue": R}),
            NodeType("Product", DIM, {"category": S}),
            NodeType("Region", DIM, {"code": S}),
        ),
        (
            EdgeType("Customer", "Sale", "placed", VERB),
            EdgeType("Product", "Sale", "included_in", VERB),
        ),
        sigma,
        kinds,
    )


def lattice(schema: DGMSchema | None = None, h: int = 2) -> QuestionLattice:
    return QuestionLattice(schema or shop(), max_anchors=3, max_hops=h)


def _request(arguments: dict[str, Any]) -> ToolCallRequest:
    bound, errors = bind_plan(plan(step("w", TOOL, arguments, fraction=1.0)))
    assert errors == []
    return bound.steps[0]


def _args(**over: Any) -> dict[str, Any]:
    base = {"dataset": "sales", "anchors": ["Customer", "Sale"], "max_hops": 1}
    return {**base, "limit": 20, **over}


def _run(
    arguments: dict[str, Any],
    sources: dict[str, Source],
    grants: Any = None,
    registry: Any = None,
) -> tuple[ToolCallResult, Opener]:
    opener = Opener(sources)
    ctx = tool_context(auth(grants), opener)  # type: ignore[arg-type]
    result = asyncio.run(
        execute_tool(_request(arguments), registry or build_registry(), ctx)
    )
    return result, opener


